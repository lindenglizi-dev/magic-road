#!/usr/bin/env python3
"""Train, quantize and export the 64-feature RTL HOG linear SVM."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image
from sklearn.metrics import accuracy_score, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import LinearSVC

from hog_reference import FEATURE_COUNT, ROI_SIZE, extract_features

IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".bmp", ".pgm", ".ppm", ".tif", ".tiff"}
CLASS_PED = 0
CLASS_VEHICLE = 1


def rtl_gray(image: Image.Image) -> np.ndarray:
    """Match (R>>2)+(G>>1)+(B>>2); preserve native grayscale images."""
    if image.mode in {"1", "L", "I", "I;16", "F"}:
        return np.asarray(image.convert("L"), dtype=np.uint8)
    rgb = np.asarray(image.convert("RGB"), dtype=np.uint16)
    return ((rgb[:, :, 0] >> 2) + (rgb[:, :, 1] >> 1) +
            (rgb[:, :, 2] >> 2)).astype(np.uint8)


def rtl_resize_32(gray: np.ndarray) -> list[list[int]]:
    """Use the same pixel-centre nearest-neighbour DDA as roi_frame_reader."""
    height, width = gray.shape
    if width < 1 or height < 1:
        raise ValueError("empty image")
    xs = np.minimum((width * (4 + 8 * np.arange(ROI_SIZE))) >> 8, width - 1)
    ys = np.minimum((height * (4 + 8 * np.arange(ROI_SIZE))) >> 8, height - 1)
    return gray[np.ix_(ys, xs)].astype(int).tolist()


def image_features(path: Path) -> list[int]:
    with Image.open(path) as image:
        roi = rtl_resize_32(rtl_gray(image))
    features, _ = extract_features(roi)
    return features


def load_dataset(root: Path) -> tuple[np.ndarray, np.ndarray, list[str]]:
    samples: list[list[int]] = []
    labels: list[int] = []
    names: list[str] = []
    for folder, label in (("ped", CLASS_PED), ("vehicle", CLASS_VEHICLE)):
        class_dir = root / folder
        if not class_dir.is_dir():
            raise ValueError(f"missing class directory: {class_dir}")
        files = sorted(path for path in class_dir.rglob("*")
                       if path.suffix.lower() in IMAGE_SUFFIXES)
        if len(files) < 4:
            raise ValueError(f"{class_dir} needs at least four images")
        for path in files:
            samples.append(image_features(path))
            labels.append(label)
            names.append(str(path))
    return np.asarray(samples, dtype=np.int64), np.asarray(labels), names


def synthetic_dataset(seed: int, count_per_class: int = 48) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """Create a deterministic smoke-test set, not a substitute for real data."""
    rng = np.random.default_rng(seed)
    samples: list[list[int]] = []
    labels: list[int] = []
    names: list[str] = []
    for label in (CLASS_PED, CLASS_VEHICLE):
        for index in range(count_per_class):
            roi = rng.integers(8, 32, size=(ROI_SIZE, ROI_SIZE), dtype=np.uint8)
            if label == CLASS_PED:
                width = int(rng.integers(5, 9))
                height = int(rng.integers(21, 28))
            else:
                width = int(rng.integers(21, 29))
                height = int(rng.integers(6, 11))
            x0 = int(rng.integers(2, ROI_SIZE - width - 1))
            y0 = int(rng.integers(2, ROI_SIZE - height - 1))
            roi[y0:y0 + height, x0:x0 + width] = int(rng.integers(170, 241))
            features, _ = extract_features(roi.astype(int).tolist())
            samples.append(features)
            labels.append(label)
            names.append(f"synthetic/{'ped' if label == 0 else 'vehicle'}/{index}")
    return np.asarray(samples, dtype=np.int64), np.asarray(labels), names


def signed_literal(width: int, value: int) -> str:
    return f"-{width}'sd{abs(value)}" if value < 0 else f"{width}'sd{value}"


def export_rom(path: Path, weights: np.ndarray, bias: int,
               weight_bits: int, accumulator_bits: int) -> None:
    cases = "\n".join(
        f"            6'd{index}: weight_value = {signed_literal(weight_bits, int(value))};"
        for index, value in enumerate(weights)
    )
    text = f"""// Generated by tools/train_hog_svm.py. Do not hand-edit weights.
module hog_svm_weights (
    input  wire [5:0] weight_address,
    output reg  signed [{weight_bits - 1}:0] weight_value,
    output wire signed [{accumulator_bits - 1}:0] bias_value
);
    assign bias_value = {signed_literal(accumulator_bits, bias)};
    always @(*) begin
        case (weight_address)
{cases}
            default: weight_value = {weight_bits}'sd0;
        endcase
    end
endmodule
"""
    path.write_text(text, encoding="ascii")


def write_hex(path: Path, values: np.ndarray, bits: int) -> None:
    mask = (1 << bits) - 1
    digits = (bits + 3) // 4
    path.write_text("".join(f"{int(value) & mask:0{digits}x}\n" for value in values),
                    encoding="ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--dataset", type=Path,
                        help="directory containing ped/ and vehicle/ image folders")
    source.add_argument("--self-test", action="store_true",
                        help="use synthetic shapes only to validate the tool chain")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--weight-bits", type=int, default=12)
    parser.add_argument("--accumulator-bits", type=int, default=40)
    parser.add_argument("--test-size", type=float, default=0.25)
    parser.add_argument("--seed", type=int, default=20260925)
    parser.add_argument("--c", type=float, default=1.0)
    parser.add_argument("--phase", choices=("fit", "test"), default="fit")
    parser.add_argument("--criteria", type=Path)
    parser.add_argument("--train-source", choices=("manual", "annotated", "ccl"), default="manual")
    parser.add_argument("--c-grid", type=float, nargs="+", default=[0.01, 0.1, 1.0, 10.0])
    args = parser.parse_args()

    if not 3 <= args.weight_bits <= 18:
        raise ValueError("weight bits must be between 3 and 18")
    if args.accumulator_bits < 32:
        raise ValueError("accumulator must be at least 32 bits")
    if args.dataset is not None:
        from road_evaluation import run
        return run(args)

    split_mode = "random_stratified"
    if args.self_test:
        features, labels, names = synthetic_dataset(args.seed)
        x_train, x_test, y_train, y_test, _, test_names = train_test_split(
            features, labels, names, test_size=args.test_size,
            random_state=args.seed, stratify=labels,
        )
    elif (args.dataset / "train").is_dir() and (args.dataset / "test").is_dir():
        x_train, y_train, train_names = load_dataset(args.dataset / "train")
        x_test, y_test, test_names = load_dataset(args.dataset / "test")
        features = np.concatenate((x_train, x_test), axis=0)
        labels = np.concatenate((y_train, y_test), axis=0)
        names = train_names + test_names
        split_mode = "explicit_train_test"
    else:
        features, labels, names = load_dataset(args.dataset)
        x_train, x_test, y_train, y_test, _, test_names = train_test_split(
            features, labels, names, test_size=args.test_size,
            random_state=args.seed, stratify=labels,
        )
    scaler = StandardScaler()
    x_train_scaled = scaler.fit_transform(x_train)
    classifier = LinearSVC(C=args.c, class_weight="balanced",
                           random_state=args.seed, max_iter=30000)
    classifier.fit(x_train_scaled, y_train)

    float_predictions = classifier.predict(scaler.transform(x_test))
    folded_weights = classifier.coef_[0] / scaler.scale_
    folded_bias = float(classifier.intercept_[0] -
                        np.dot(classifier.coef_[0], scaler.mean_ / scaler.scale_))

    max_integer_weight = (1 << (args.weight_bits - 1)) - 1
    max_abs_weight = float(np.max(np.abs(folded_weights)))
    if max_abs_weight == 0.0:
        raise ValueError("trained model has zero weights")
    quant_scale = max_integer_weight / max_abs_weight
    quant_weights = np.rint(folded_weights * quant_scale).astype(np.int64)
    quant_bias = int(round(folded_bias * quant_scale))
    quant_scores = features @ quant_weights + quant_bias
    quant_predictions = (quant_scores >= 0).astype(np.int64)
    test_indices = np.array([names.index(name) for name in test_names])
    quant_test_predictions = quant_predictions[test_indices]

    theoretical_feature_max = 64 * 2040
    worst_score_bound = (abs(quant_bias) +
                         int(np.sum(np.abs(quant_weights))) * theoretical_feature_max)
    accumulator_limit = (1 << (args.accumulator_bits - 1)) - 1
    if worst_score_bound > accumulator_limit:
        raise ValueError(
            f"{args.accumulator_bits}-bit accumulator may overflow: "
            f"bound={worst_score_bound}, limit={accumulator_limit}"
        )

    output = args.output
    output.mkdir(parents=True, exist_ok=True)
    export_rom(output / "hog_svm_weights.v", quant_weights, quant_bias,
               args.weight_bits, args.accumulator_bits)
    write_hex(output / "hog_svm_weights.hex", quant_weights, args.weight_bits)

    # Export one exact vector so generated ROM and RTL MAC can be tested together.
    vector = x_test[0]
    expected_score = int(np.dot(vector, quant_weights) + quant_bias)
    expected_class = 2 if expected_score >= 0 else 1
    write_hex(output / "svm_test_feature.hex", vector, 18)
    write_hex(output / "svm_test_score.hex", np.asarray([expected_score]),
              args.accumulator_bits)
    write_hex(output / "svm_test_class.hex", np.asarray([expected_class]), 2)

    metrics = {
        "warning": "synthetic self-test is tool validation only" if args.self_test else None,
        "split_mode": split_mode,
        "sample_count": int(len(features)),
        "ped_count": int(np.sum(labels == CLASS_PED)),
        "vehicle_count": int(np.sum(labels == CLASS_VEHICLE)),
        "feature_count": FEATURE_COUNT,
        "float_test_accuracy": float(accuracy_score(y_test, float_predictions)),
        "quantized_test_accuracy": float(accuracy_score(y_test, quant_test_predictions)),
        "float_confusion_matrix": confusion_matrix(y_test, float_predictions).tolist(),
        "quantized_confusion_matrix": confusion_matrix(y_test, quant_test_predictions).tolist(),
        "weight_bits": args.weight_bits,
        "accumulator_bits": args.accumulator_bits,
        "quantization_scale": quant_scale,
        "quantized_bias": quant_bias,
        "worst_score_bound": worst_score_bound,
        "test_vector_name": test_names[0],
        "test_vector_score": expected_score,
        "test_vector_class": expected_class,
    }
    (output / "metrics.json").write_text(
        json.dumps(metrics, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (output / "model.json").write_text(
        json.dumps({
            "feature_order": "{cell_y[1:0], cell_x[1:0], bin[1:0]}",
            "negative_class": "pedestrian/RTL class 1",
            "positive_class": "vehicle/RTL class 2",
            "float_folded_weights": folded_weights.tolist(),
            "float_folded_bias": folded_bias,
            "quantized_weights": quant_weights.tolist(),
            "quantized_bias": quant_bias,
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    print(json.dumps(metrics, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
